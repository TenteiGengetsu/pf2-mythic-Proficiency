  await open();
  assert.equal(await page.locator("input[data-mythic-choice]").count(), 2);
  assert.equal(await page.locator("label.mythic-radio-control").count(), 2);
  assert.equal(await page.locator("label.mythic-radio-control .widget, label.toggle input[type=radio]").count(), 0);
