  assert.ok((await page.locator("button[type=submit]").textContent()).includes("24"));
  assert.equal(await page.evaluate(() => actor.getResource().value), 3);
  await choice("normal").click(); assert.ok((await page.locator("button[type=submit]").textContent()).includes("16"));
  pass("radio choices are exclusive and switching recalculates the total without spending points");
